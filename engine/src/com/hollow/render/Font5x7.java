/** HollowEngine 2 — hand-authored 5x7 bitmap font for HUD text
 *  (A-Z, 0-9, punctuation). Lowercase maps to uppercase; unknown
 *  characters render as space. Each glyph is 7 rows of 5 bits,
 *  row-major, LSB = rightmost pixel of the row. */
